import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
import { mkdir } from 'node:fs/promises';
import { serve } from '../scripts/serve.mjs';
const server=serve(undefined,4173);
await new Promise(resolve=>server.on('listening',resolve));
const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL?{channel:process.env.PLAYWRIGHT_CHANNEL}:{})});
await mkdir('test-results',{recursive:true});
let checks=0;
const check=(condition,label)=>{assert.ok(condition,label);checks++;console.log('PASS:',label);};
try {
  for(const [name,width,height] of [['mobile',390,844],['tablet',820,1180],['desktop',1440,1000]]){
    const page=await browser.newPage({viewport:{width,height}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:4173/');
    check(await page.locator('.service-card').count()===6,`${name}: six services`);
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${name}: no horizontal overflow`);
    if(name==='mobile'){
      await page.getByRole('button',{name:'Menu'}).click();
      check(await page.locator('nav').isVisible(),'mobile: menu opens');
      await page.keyboard.press('Escape');check(!(await page.locator('nav').isVisible()),'mobile: Escape closes menu');
    }
    await page.locator('[data-service="Dashboards"]').click();
    check(await page.locator('#enquiry-service').inputValue()==='Dashboards',`${name}: service selection`);
    const pdf=await page.request.get('http://127.0.0.1:4173/assets/SP-Raja-CV.pdf');
    check(pdf.ok()&&(await pdf.body()).subarray(0,4).toString()==='%PDF',`${name}: CV download`);
    await page.screenshot({path:`test-results/portfolio-${name}.png`,fullPage:true});
    await page.goto('http://127.0.0.1:4173/portal.html');
    await page.locator('#unavailable').waitFor({state:'visible'});
    check(!(await page.locator('#auth-panel').isVisible()),`${name}: unconfigured auth stays unavailable`);
    check(errors.length===0,`${name}: no JavaScript errors`);
    await page.close();
  }
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const id='11111111-1111-4111-8111-111111111111';
  const user={id,email:'customer@example.test',email_confirmed_at:'2026-10-12T00:00:00Z',aud:'authenticated',role:'authenticated',user_metadata:{full_name:'Customer Example'}};
  const jwt=`${Buffer.from(JSON.stringify({alg:'HS256',typ:'JWT'})).toString('base64url')}.${Buffer.from(JSON.stringify({sub:id,exp:Math.floor(Date.now()/1000)+3600,role:'authenticated'})).toString('base64url')}.test-signature`;
  const session={access_token:jwt,refresh_token:'test-refresh',token_type:'bearer',expires_in:3600,user};
  const calls=[];let failRequest=false;
  await page.route('**/config.json',r=>r.fulfill({json:{supabaseUrl:'https://portal-test.supabase.co',supabasePublishableKey:'sb_publishable_test'}}));
  await page.route('https://portal-test.supabase.co/**',async route=>{
    const request=route.request(),url=new URL(request.url());calls.push({path:url.pathname,body:request.postDataJSON()});
    if(url.pathname==='/auth/v1/user')return route.fulfill({json:user});
    if(url.pathname==='/auth/v1/token')return route.fulfill({json:session});
    if(url.pathname==='/auth/v1/signup')return route.fulfill({json:{user,session:null}});
    if(url.pathname==='/auth/v1/logout')return route.fulfill({status:204});
    if(url.pathname==='/rest/v1/rpc/submit_enquiry')return failRequest?route.fulfill({status:500,json:{message:'database unavailable'}}):route.fulfill({json:'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'});
    if(url.pathname==='/rest/v1/enquiries')return route.fulfill({json:[{id:'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',service:'Dashboards',message:'<img src=x onerror="window.injected=true">',status:'submitted',created_at:'2026-10-12T00:00:00Z'}]});
    return route.fulfill({json:{}});
  });
  await page.goto('http://127.0.0.1:4173/portal.html');
  await page.locator('#auth-panel').waitFor({state:'visible'});
  await page.locator('[data-view="register"]').click();
  const registration=page.locator('#register-form');
  await registration.locator('[name=name]').fill('Customer Example');await registration.locator('[name=email]').fill(user.email);
  await registration.locator('[name=password]').fill('a-long-test-password');await registration.locator('[name=confirm]').fill('a-different-password');
  await registration.locator('[type=checkbox]').check();await registration.locator('[type=submit]').click();
  check((await registration.locator('.feedback').textContent()).includes('do not match'),'registration: mismatched passwords rejected');
  check(!calls.some(c=>c.path==='/auth/v1/signup'),'registration: mismatch never sent');
  await registration.locator('[name=confirm]').fill('a-long-test-password');await registration.locator('[type=submit]').click();
  await page.locator('#verify-form').waitFor({state:'visible'});check(true,'registration: verification instructions shown');
  await page.locator('#verify-form [type=submit]').click();await page.waitForFunction(()=>document.querySelector('#verify-form .feedback').textContent.includes('If verification'));
  check(calls.some(c=>c.path==='/auth/v1/resend'),'registration: resend supported');
  await page.locator('[data-view=recover]').click();await page.locator('#recover-form [name=email]').fill('unknown@example.test');await page.locator('#recover-form [type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#recover-form .feedback').textContent.includes('If this address'));
  check(true,'recovery: response does not reveal account existence');
  await page.locator('[data-view=login]').click();await page.locator('#login-form [name=email]').fill(user.email);await page.locator('#login-form [name=password]').fill('a-long-test-password');await page.locator('#login-form [type=submit]').click();
  await page.locator('#dashboard').waitFor({state:'visible'});await page.locator('.request-item').waitFor();
  check(!(await page.evaluate(()=>window.injected)),'dashboard: enquiry text cannot execute HTML');
  check((await page.locator('.request-item').textContent()).includes('<img'),'dashboard: enquiry text rendered safely');
  const request=page.locator('#request-form');await request.locator('[name=service]').selectOption('Dashboards');await request.locator('[name=message]').fill('Please create a dashboard for monthly reporting.');
  failRequest=true;await request.locator('[type=submit]').click();await page.waitForFunction(()=>document.querySelector('#request-form .feedback').classList.contains('error'));
  check(!(await request.locator('.feedback').textContent()).includes('saved'),'enquiry: failure is not reported as success');
  failRequest=false;await request.locator('[type=submit]').click();await page.waitForFunction(()=>document.querySelector('#request-form .feedback').textContent.includes('is saved'));
  const submissions=calls.filter(c=>c.path==='/rest/v1/rpc/submit_enquiry');
  check(submissions[0].body.p_request_id===submissions[1].body.p_request_id,'enquiry: network retry keeps idempotency key');
  await page.screenshot({path:'test-results/customer-dashboard.png',fullPage:true});
  await page.locator('#sign-out').click();await page.locator('#auth-panel').waitFor({state:'visible'});
  check(await page.locator('.request-item').count()===0,'sign-out: customer records cleared from DOM');
  await page.goto(`http://127.0.0.1:4173/portal.html?recovery=1#access_token=${jwt}&refresh_token=test-refresh&expires_in=3600&token_type=bearer&type=recovery`);
  await page.locator('#password-panel').waitFor({state:'visible'});
  await page.locator('#password-form [name=password]').fill('a-new-long-test-password');await page.locator('#password-form [name=confirm]').fill('a-new-long-test-password');await page.locator('#password-form [type=submit]').click();
  await page.locator('#auth-panel').waitFor({state:'visible'});
  check(calls.some(c=>c.path==='/auth/v1/user'&&c.body?.password==='a-new-long-test-password'),'recovery: password update sent to authentication provider');
  check(!(await page.evaluate(()=>location.hash.includes('access_token'))),'recovery: tokens removed from address bar');
  check(errors.length===0,'customer flows: no JavaScript errors');
  console.log(`Browser checks passed: ${checks}. Auth responses are mocked; no email was sent.`);
} finally {await browser.close(); await new Promise(resolve=>server.close(resolve));}
